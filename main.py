def solve_problem_1(n):
    """
    Решение проблемы 1: Вычисление факториала числа n.

    Факториал числа n (обозначается n!) — это произведение всех натуральных чисел от 1 до n включительно.
    Например, 5! = 1 * 2 * 3 * 4 * 5 = 120.

    Args:
        n (int): Положительное целое число.

    Returns:
        int: Факториал числа n.

    Raises:
        ValueError: Если n отрицательное.
    """
    if n < 0:
        raise ValueError("Факториал не определен для отрицательных чисел")
    if n == 0 or n == 1:
        return 1
    result = 1
    for i in range(2, n + 1):
        result *= i  # Умножаем результат на текущее число
    return result

def solve_problem_2(numbers):
    """
    Решение проблемы 2: Поиск максимального элемента в списке.

    Функция находит наибольшее число в переданном списке.

    Args:
        numbers (list): Список чисел.

    Returns:
        int or float: Максимальное значение в списке.

    Raises:
        ValueError: Если список пустой.
    """
    if not numbers:
        raise ValueError("Список не может быть пустым")
    max_value = numbers[0]  # Предполагаем, что первый элемент максимальный
    for num in numbers[1:]:
        if num > max_value:
            max_value = num  # Обновляем максимум, если нашли большее число
    return max_value

def solve_problem_3(arr):
    """
    Решение проблемы 3: Сортировка списка пузырьком.

    Пузырьковая сортировка - простой алгоритм сортировки, который многократно проходит по списку,
    сравнивает соседние элементы и меняет их местами, если они находятся в неправильном порядке.

    Args:
        arr (list): Список для сортировки.

    Returns:
        list: Отсортированный список.
    """
    n = len(arr)
    for i in range(n):
        # Последние i элементов уже на месте
        for j in range(0, n - i - 1):
            if arr[j] > arr[j + 1]:
                # Меняем местами, если элемент больше следующего
                arr[j], arr[j + 1] = arr[j + 1], arr[j]
    return arr

